/* ============================================================================
 * 功能区：通用工具 / id 开始
 * 职责：标识生成：创建会话、消息与本地记录所需的唯一 ID。
 * 导出：createId。
 * ========================================================================== */

export const createId = () =>
  typeof crypto.randomUUID === 'function'
    ? crypto.randomUUID()
    : `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`

