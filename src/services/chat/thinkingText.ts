/* ---- 02 文本归一 ---- */
/**
 * 写作计划句式：模型在搜索/深度思考轮常把提示词当成任务清单复述，
 * 例如「我得用人物身份接住」「我会用第一人称并加入语气词」「现在开始组织回答」。
 * 这类句子整句丢弃，避免思考面板出现模型视角的计划稿；只匹配明确措辞，不误伤剧情叙述。
 */
const META_SENTENCE_PATTERNS: readonly RegExp[] = [
  // 把自己当成第三者的演法指令：以人物口吻 / 用角色身份 / 保持人设
  /(用|以)[^。；！？\n]{0,4}(人物|角色)(的)?(身份|口吻|语气)/,
  /(人物|角色)(的)?(口吻|语气|身份)[^。；！？\n]{0,12}(说|讲|写|回复|回答)/,
  /(保持|维持)(人物|角色|人设|设定)/,
  /(第一人称|第三人称|语气词|旁白腔|客服腔)/,
  // 「我应该……带点语气/称呼/客服/列点」这类给自己下写作指令的句子
  /^(我)?(应该|该|需要|得|要|可以|不能|不要|别|避免|注意|记得)[^。；！？\n]{0,50}(口吻|语气|称呼|客服|人设|人物|角色|第一人称|第三人称|列点|列得|格式|篇幅|语气词)/,
  // 「现在写回复 / 接下来组织回答 / 最后来一段介绍」
  /^(现在|接下来|然后|最后|下面)[^。；！？\n]{0,20}(写|组织|整理|开始|来)[^。；！？\n]{0,10}(回复|回答|答复)/,
  /^(现在|接下来|然后|最后)?(写|组织|整理|开始写|准备写)(回复|回答|答复)/,
  /(我会|还会|也会|先|再)(先|再|接着)?(提到|说到|讲到|聊到|介绍)/,
  /(组织|整理|构思)(一下)?(回答|回复|语言|措辞|内容)/,
  /(列|写)(一下)?(提纲|大纲|要点)/,
  /^不用(列|写|说)得?/,
  /^注意(不要|别)(用|说|写|提)[“"「]/,
  /(助手|客服)(口吻|语气|腔)|客服式/,
  /^(可以|要|得|应该)[^。；！？\n]{0,16}(抱怨|感叹|撒娇|卖萌|停顿)[^。；！？\n]{0,6}(点|些|一下)?/,
  /按(时间线|活动类型|类型|分类|类别)[^。；！？\n]{0,6}(组织|整理|排列)/,
  /转述[^。；！？\n]{0,6}(检索|搜索|查到|资料|结果)/,
  // 检索轮常见的助手式调度：搜索计划、工具播报、结果概述、回答结构
  /^我需要(搜索|查询|查找|核实|确认|打开|浏览|获取|整理)/,
  /^(但|不过)?(我)?(需要|得|要)(联网|搜索|查|打开|浏览|核实|确认)/,
  /^为了[^。；！？\n]{0,32}(搜索|检索|获取|覆盖|信息|准确|全面)/,
  /^我们(需要|要|可以|将|先|再|来)/,
  /^(搜索|检索|查询)(结果|到的?页面|到的?内容)(显示|表明|里|中|告诉|提到|包含)/,
  /^(打开|浏览|翻阅)(这些|那些|几个)?(页面|链接|网页)/,
  /^这些?(页面|链接|网页)(提供|包含|显示|提到)/,
  /^回答(中|里)?(要|需要|必须|应该)/,
  /^我(会|打算|准备)(先|再|接着|然后|最后)?[^。；！？\n]{0,24}(回答|回复|介绍|说明|提到|给出|罗列|列成)/,
  /^最后(再)?(可以|要|应该)(问|提|补充|加)/,
  /^像在跟[^。；！？\n]{0,24}(分享|说|讲)/,
  /^(但|不过)?可以自然(地)?说/,
  /(以|用)(角色|人物)[“"「]?[^。；！？\n]{0,10}[”"」]?(的)?(口吻|身份|语气)[^。；！？\n]{0,10}(组织|写|说|回答|回复)/,
]

/**
 * 「用户想了解…」「玩家想知道…」是模型对需求的旁白，不是人物心声，整句丢弃。
 * 带昵称的说法（「小满想知道…」）会在后面改成第二人称「你…」，保留成人物心里的念叨，
 * 不把对方写成第三人称。
 */
const isUserIntentMeta = (sentence: string): boolean =>
  /^(用户|玩家)(想|想要|希望|需要|打算)(了解|知道|查询|查|找|问|看)/.test(sentence.trim())

/** 按句切分后整句过滤写作计划；保留原有换行结构 */
const dropPlanSentences = (text: string, userName: string): string => {
  const name = userName.trim()
  // 「称呼小满。」是模型对自己的指令，不是人物心声；只抹掉恰好由昵称构成的那一句。
  const nameInstruction =
    name && !PLACEHOLDER_NAMES.has(name)
      ? new RegExp(
          `^(称呼|叫)${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[。；！？]?$`
        )
      : null
  return text
    .split('\n')
    .map((line) =>
      Array.from(line.matchAll(/[^。；！？]+[。；！？]?/g))
        .map(([sentence]) => sentence)
        .filter(
          (sentence) =>
            !META_SENTENCE_PATTERNS.some((pattern) => pattern.test(sentence)) &&
            !nameInstruction?.test(sentence.trim()) &&
            !isUserIntentMeta(sentence)
        )
        .join('')
    )
    .join('\n')
}

const scrubMeta = (text: string, userName: string): string => {
  const name = userName.trim()
  let out = dropPlanSentences(text, name)
  for (const phrase of META_PHRASES) {
    out = out.replaceAll(phrase, '')
  }
  // 人物心里提到对方时用「你」，不写成「小满想知道…」这种第三人称旁白。
  if (name && !PLACEHOLDER_NAMES.has(name)) {
    const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    out = out.replace(
      new RegExp(
        `(^|[。；！？\n])${escaped}(?=(想|想要|希望|需要|打算)(了解|知道|查询|查|找|问|看))`,
        'gm'
      ),
      '$1你'
    )
  }
  // 清理抹除后残留的悬空顿号、重复空白与多余空行
  out = out.replace(/([。；！？])[，,、]+/g, '$1')
  out = out.replace(/[，,、]\s*[，,、]+/g, '，')
  out = out.replace(/^[，,、：:\s]+/, '')
  out = out.replace(/[ \t]{2,}/g, ' ')
  out = out.replace(/\n{3,}/g, '\n\n')
  return out.trim()
}

/** 名字紧邻重复（可夹顿号、逗号与空格）合并成一次：小满小满 / 小满、小满 → 小满 */
const collapseRepeatedName = (text: string, name: string): string => {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const pattern = new RegExp(`(${escaped})(?:[、,，\\s]{0,2}\\1)+`, 'g')
  return text.replace(pattern, '$1')
}

/**
 * 思考链展示归一：
 * - 先整句丢弃写作计划/任务清单式措辞；
 * - 再抹除元分析 / 意图揣测类短语；
 * - 把“用户 / 玩家 / User”这类泛称换成当前账号昵称（昵称为空或占位名时不替换）；
 * - 最后合并紧邻重复的名字，避免出现「小满小满」。
 * 不改动原始本地记录，也不用于回传上下文。
 */
export const sanitizeThinkingText = (raw: string, userName: string): string => {
  if (!raw) {
    return raw
  }
  const name = userName.trim()
  let text = scrubMeta(raw, name)
  if (name && !PLACEHOLDER_NAMES.has(name)) {
    text = text
      .replaceAll('玩家', name)
      .replaceAll('用户', name)
      .replace(/\bUser\b/gi, name)
    text = collapseRepeatedName(text, name)
  }
  return text.trim()
}
