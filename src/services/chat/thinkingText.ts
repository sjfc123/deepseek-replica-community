/**
 * 「用户想了解…」「玩家想知道…」是模型对需求的旁白，不是人物心声，整句丢弃。
 * 带昵称的说法（「小满想知道…」）会在后面改成第二人称「你…」，保留成人物心里的念叨，
 * 不把对方写成第三人称。
 */
const isUserIntentMeta = (sentence: string): boolean =>
  /^(用户|玩家)(想|想要|希望|需要|打算)(了解|知道|查询|查|找|问|看)/.test(sentence.trim())

/** 按句切分后整句过滤写作计划；保留原有换行结构 */
const dropPlanSentences = (text: string, userName: string): string => {
  const name = userName.trim()
  // 「称呼小满。」是模型对自己的指令，不是人物心声；只抹掉恰好由昵称构成的那一句。
  const nameInstruction =
    name && !PLACEHOLDER_NAMES.has(name)
      ? new RegExp(
          `^(称呼|叫)${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[。；！？]?$`
        )
      : null
  return text
    .split('\n')
    .map((line) =>
      Array.from(line.matchAll(/[^。；！？]+[。；！？]?/g))
        .map(([sentence]) => sentence)
        .filter(
          (sentence) =>
            !META_SENTENCE_PATTERNS.some((pattern) => pattern.test(sentence)) &&
            !nameInstruction?.test(sentence.trim()) &&
            !isUserIntentMeta(sentence)
        )
        .join('')
    )
    .join('\n')
}

const scrubMeta = (text: string, userName: string): string => {
  const name = userName.trim()
  let out = dropPlanSentences(text, name)
  for (const phrase of META_PHRASES) {
    out = out.replaceAll(phrase, '')
  }
  // 人物心里提到对方时用「你」，不写成「小满想知道…」这种第三人称旁白。
  if (name && !PLACEHOLDER_NAMES.has(name)) {
    const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    out = out.replace(
      new RegExp(
        `(^|[。；！？\n])${escaped}(?=(想|想要|希望|需要|打算)(了解|知道|查询|查|找|问|看))`,
        'gm'
      ),
      '$1你'
    )
  }
  // 清理抹除后残留的悬空顿号、重复空白与多余空行
  out = out.replace(/([。；！？])[，,、]+/g, '$1')
  out = out.replace(/[，,、]\s*[，,、]+/g, '，')
  out = out.replace(/^[，,、：:\s]+/, '')
  out = out.replace(/[ \t]{2,}/g, ' ')
  out = out.replace(/\n{3,}/g, '\n\n')
  return out.trim()
}

