const SENTENCE_RE = /[^。；！？\n]+[。；！？]?/g

const escapeRegExp = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** 把“用户 / 玩家 / User / 对方”统一成当前用户名；用户名是占位名时保持原样。 */
const normalizeUserReferences = (text: string, name: string): string => {
  if (!name || PLACEHOLDER_NAMES.has(name)) {
    return text
  }
  const escaped = escapeRegExp(name)
  let out = text
    .replaceAll('玩家', name)
    .replaceAll('用户', name)
    .replace(/\bUser\b/gi, name)
    // 用户名后面再跟“他/她/本人”，视作同一个人，收成一次
    .replace(new RegExp(`(${escaped})(?:他|她|本人|这个人)`, 'g'), '$1')
    // “阿岚说他累了”收成“阿岚说累了”，不把用户写成第三人称旁白
    .replace(new RegExp(`(${escaped})\\s*说(?:他|她)`, 'g'), '$1说')
    // “阿岚要求我查”改成“阿岚让我查”，保留人物语气，不保留模型的任务口吻
    .replace(new RegExp(`(${escaped})\\s*要求我(查|搜|找|说|讲|回答|确认)`, 'g'), '$1让我$2')
  // 第一人称认知/情绪动词后面的“他/她”，在单用户对话里按用户名处理；亲属、朋友等第三人称保留
  out = out.replace(
    new RegExp(
      `(我(?:不知道|觉得|担心|怕|在想|猜|看|听|知道|心疼|记得))[，。]?(?:他|她)(?!的?(?:妈|爸|家|朋友|同事|老板|老公|老婆|孩子))`,
      'g'
    ),
    `$1${name}`
  )
  // 没有其他在场者提示时，才把“对方”收成用户名；多角色场景交给模型用具体名字
  if (!/(他们|她们|其他人|另一个|旁边|在场|身后|身边|对面|老板|同事|朋友|家人)/.test(out)) {
    out = out.replaceAll('对方', name)
  }
  // 单用户整段里，人物已用名字出现时，把剩下的单数他/她收成名字；
  // 出现老板、同事、家人等其他角色时不动，交给模型用具体身份。
  const namePattern = new RegExp(escaped)
  const replacePronouns = (text: string) =>
    text.replace(/(?<!其)他(?!们)/g, name).replace(/(?<!其)她(?!们)/g, name)
  if (namePattern.test(out) && !OTHER_ROLE_MARKERS.test(out)) {
    out = replacePronouns(out)
  }
  return out
}

const stripLabelPrefix = (clause: string): string =>
  clause.replace(/^(天气|气温|日期|时间|场馆|票价|地点|资料|信息)(情况)?[：:]\s*/, '')

/** 只删句子里的计划片段，保留同一句里的人物反应与判断。 */
const cleanSentence = (sentence: string, name: string): string => {
  const trimmed = sentence.trim()
  if (!trimmed) {
    return ''
  }
  if (HARD_META_SENTENCE_PATTERNS.some((pattern) => pattern.test(trimmed))) {
    return ''
  }
  // 检索工作笔记：只有资料词、没有人物情绪，整句丢弃
  if (isWorkNoteSentence(trimmed)) {
    return ''
  }
  if (isFactSentence(trimmed)) {
    return ''
  }
  if (isStrategySentence(trimmed)) {
    return ''
  }
  // 整句都是写作计划/检索调度时整句丢弃；只丢这一句，不连带整段人物心声
  if (META_SENTENCE_PATTERNS.some((pattern) => pattern.test(trimmed))) {
    return ''
  }
  const end = trimmed.match(/[。；！？]?$/)?.[0] ?? ''
  const body = end ? trimmed.slice(0, -end.length) : trimmed
  const clauses = body
    .split(/[，,]/)
    .map((clause) => clause.trim())
    .filter(Boolean)
  const escaped = name ? escapeRegExp(name) : ''
  const nameInstruction =
    name && escaped
      ? new RegExp(`^((先|再)?叫|称呼)${escaped}[。；！？]?$`)
      : null
  const kept: string[] = []
  for (const clause of clauses) {
    const normalized = stripLabelPrefix(clause)
    if (!normalized) {
      continue
    }
    if (nameInstruction?.test(normalized)) {
      continue
    }
    if (EXTRA_PLAN_CLAUSE_PATTERNS.some((pattern) => pattern.test(normalized))) {
      continue
    }
    kept.push(normalized)
  }
  if (kept.length === 0) {
    return ''
  }
  return kept.join('，') + end
}

const scrubMeta = (text: string, userName: string): string => {
  const name = userName.trim()
  let out = normalizeUserReferences(text, name)
  for (const phrase of META_PHRASES) {
    out = out.replaceAll(phrase, '')
  }
  // 逐句、逐片段清理计划措辞；同一句里的人物反应保留下来
  out = out
    .split('\n')
    .map((line) =>
      Array.from(line.matchAll(SENTENCE_RE))
        .map(([sentence]) => cleanSentence(sentence, name))
        .join('')
    )
    .join('\n')
  // 清理抹除后残留的悬空顿号、重复空白与多余空行
  out = out.replace(/([。；！？])[，,、]+/g, '$1')
  out = out.replace(/[，,、]\s*[，,、]+/g, '，')
  out = out.replace(/^[，,、：:\s]+/, '')
  out = out.replace(/[ \t]{2,}/g, ' ')
  out = out.replace(/\n{3,}/g, '\n\n')
  return out.trim()
}

/** 整句删除后常留下悬空的右括号/右引号，展示前收一下，避免思考面板出现半个括号 */
const tidyBrackets = (text: string): string =>
  text
    .split('\n')
    .map((line) => {
      let l = line.trim()
      while (
        l.endsWith('）') &&
        (l.match(/（/g)?.length ?? 0) < (l.match(/）/g)?.length ?? 0)
      ) {
        l = l.slice(0, -1).trimEnd()
      }
      while (l.startsWith('）')) {
        l = l.slice(1).trimStart()
      }
      if (l.startsWith('（') && (l.match(/（/g)?.length ?? 0) > (l.match(/）/g)?.length ?? 0)) {
        l = l.slice(1).trimStart()
      }
      while (/^[）)】]/.test(l)) {
        l = l.slice(1).trimStart()
      }
      while (/^[。；，、！？]/.test(l)) {
        l = l.slice(1).trimStart()
      }
      if (/^[。；，、！？]+$/.test(l)) {
        return ''
      }
      l = l.replace(/。{2,}/g, '。')
      if (l.startsWith('"') && (l.match(/"/g)?.length ?? 0) % 2 === 1) {
        l = l.slice(1)
      }
      for (const [open, close] of [
        ['"', '"'],
        ['“', '”'],
      ]) {
        const opens = l.match(new RegExp(open, 'g'))?.length ?? 0
        const closes = l.match(new RegExp(close, 'g'))?.length ?? 0
        const uneven = open === close ? opens % 2 === 1 : opens !== closes
        if (uneven) {
          l = l.replaceAll(open, '').replaceAll(close, '')
        }
      }
      if (l.startsWith('（') && (l.match(/（/g)?.length ?? 0) > (l.match(/）/g)?.length ?? 0)) {
        l += '）'
      }
      return l
    })
    .filter(Boolean)
    .join('\n')

/** 名字紧邻重复（可夹顿号、逗号与空格）合并成一次：小满小满 / 小满、小满 → 小满 */
const collapseRepeatedName = (text: string, name: string): string => {
  const escaped = escapeRegExp(name)
  const pattern = new RegExp(`(${escaped})(?:[、,，\\s]{0,2}\\1)+`, 'g')
  const parenthesized = new RegExp(`(${escaped})(?:（\\1）|\\\\(\\1\\\\))`, 'g')
  return text.replace(pattern, '$1').replace(parenthesized, '$1')
}

