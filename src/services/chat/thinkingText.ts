/* ---- 01 占位名与元分析短语 ---- */
/** 账号名为空或落在这些占位名上时，不做昵称替换，回落默认“用户” */
const PLACEHOLDER_NAMES = new Set(['用户', '本地用户', 'Local user', 'local user'])

